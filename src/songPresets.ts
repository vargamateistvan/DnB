import type { KitId, MachineParams } from './types'
import type { PresetStep } from './presets'

export interface SongPreset {
  name: string
  artist: string
  bpm: number
  stepCount?: 16 | 32 | 64
  activeKits: KitId[]
  machineParams?: Partial<{ [K in KitId]: Partial<MachineParams[K]> }>
  tracks: Partial<Record<string, PresetStep[]>>
}

function s(indices: number[], velocity = 0.8): PresetStep[] {
  return indices.map((index) => ({ index, velocity }))
}
function b(data: Array<[number, string, number?]>): PresetStep[] {
  return data.map(([index, note, velocity = 0.8]) => ({ index, note, velocity }))
}

